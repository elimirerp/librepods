#!/usr/bin/env python3
"""Capture native generic STS descriptors with synthetic IV/cycle inputs.
The MMIO engine is not emulated. No generated bytes or AES equivalence claimed.
"""
import json,struct
from pathlib import Path
from unicorn import *
from unicorn.arm_const import *
IMAGE=Path(__file__).resolve().parent.parent/'airpods-pro3-firmware-agent/A3122-rose/rkos.bin'
BASE,RAM,STOP=0x400000,0x10000000,0x4f0000
REGS=[UC_ARM_REG_R0,UC_ARM_REG_R1,UC_ARM_REG_R2,UC_ARM_REG_R3]
def capture(cycle,offset,length):
 u=Uc(UC_ARCH_ARM,UC_MODE_THUMB|UC_MODE_MCLASS)
 u.mem_map(BASE,0x100000);u.mem_write(BASE,IMAGE.read_bytes())
 u.mem_map(RAM,0x40000);u.mem_map(0x44005000,0x1000)
 key,iv,out,sp=RAM+0x3100,RAM+0x3200,RAM+0x1000,RAM+0x3e000
 u.mem_write(key,bytes(range(16)));seed=bytes.fromhex('000203040506070800000000000000ff');u.mem_write(iv,seed)
 u.mem_write(sp,struct.pack('<II',offset,length));u.mem_write(0x44005014,struct.pack('<I',1))
 writes=[]
 def ret(v=0):u.reg_write(UC_ARM_REG_R0,v);u.reg_write(UC_ARM_REG_PC,u.reg_read(UC_ARM_REG_LR))
 def code(uc,a,s,_):
  if a==STOP:uc.emu_stop()
  elif a==0x406950:
   d,src,n=[uc.reg_read(r) for r in REGS[:3]];uc.mem_write(d,bytes(uc.mem_read(src,n)));ret(d)
 def mem(uc,access,a,s,v,_):
  if a==0x44005020:
   writes.append({'word':hex(v),'ivCopy':bytes(uc.mem_read(RAM+0x31008,16)).hex()})
 u.hook_add(UC_HOOK_CODE,code);u.hook_add(UC_HOOK_MEM_WRITE,mem)
 for r,v in zip(REGS,[key,iv,cycle,out]):u.reg_write(r,v)
 u.reg_write(UC_ARM_REG_SP,sp);u.reg_write(UC_ARM_REG_LR,STOP|1)
 u.emu_start(0x41ffa0|1,STOP+2,count=10000)
 words=[int(x['word'],16) for x in writes]
 expected=[];remaining=length;ptr=out
 while remaining:
  n=min(remaining,1024);expected += [0x16000000,key,0x26000000|(n<<8),RAM+0x31008,cycle,ptr]
  ptr+=n;remaining-=n
 assert words==expected,(words,expected)
 blocks=[writes[i:i+6] for i in range(0,len(writes),6)]
 return {'cycleArgument':hex(cycle),'offsetBytes':offset,'requestedBytes':length,
         'descriptors':[{'words':[x['word'] for x in block],'ivAtSubmission':block[-1]['ivCopy']} for block in blocks]}
rows=[capture(c,16,n) for c,n in [(0x2056c539,512),(0x1234,1040)]]
assert rows[0]['descriptors'][0]['ivAtSubmission'].endswith('00000100')
assert rows[1]['descriptors'][1]['ivAtSubmission'].endswith('00000140')
print(json.dumps({'scope':__doc__,'results':rows,'aesEmulated':False},indent=2))
